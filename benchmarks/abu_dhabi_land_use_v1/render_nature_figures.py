def load_json(name: str):
    with (ROOT / name).open("r", encoding="utf-8") as handle:
        return json.load(handle)


def _require_current_report(name: str, *, metric_version: str) -> dict:
    """Load a report only when it was generated by the revised evaluator.

    Legacy JSON files are retained for lineage, but rendering them as if they
    were current evidence would silently recreate the problem identified in
    the review.  Figure generation therefore fails closed until the source
    rasters and revised compiler outputs are present.
    """

    path = ROOT / name
    if not path.is_file():
        raise RuntimeError(f"figure_render_blocked:missing_report:{name}")
    report = load_json(name)
    if report.get("metric_version") != metric_version:
        raise RuntimeError(
            "figure_render_blocked:stale_report:"
            f"{name}:{report.get('metric_version')}"
        )
    if report.get("revision_status") != "rerun_from_current_rasters":
        raise RuntimeError(
            "figure_render_blocked:unverified_report:"
            f"{name}:{report.get('revision_status')}"
        )
    return report


def _require_file(relative_path: str) -> None:
    if not (ROOT / relative_path).is_file():
        raise RuntimeError(f"figure_render_blocked:missing_input:{relative_path}")


