#!/usr/bin/env python3
"""Fail-closed check for a clean, rerunnable benchmark checkout.

Reports already generated by another machine are never treated as evidence of
reproducibility. The gate checks the vendored runtimes, the minimal public
input bundle, the checkpoints, the exact dependency lock and every SHA-256 in
``reproducibility/MANIFEST.json``.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import platform
import sys
from datetime import UTC, datetime
from pathlib import Path


HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
MANIFEST = HERE / "reproducibility/MANIFEST.json"
SUMS = HERE / "reproducibility/SHA256SUMS"


def _display(path: Path) -> str:
    try:
        return path.resolve().relative_to(REPO.resolve()).as_posix()
    except ValueError:
        return f"external/{path.name}"


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _manifest_checks() -> tuple[dict[str, bool], list[dict[str, object]]]:
    if not MANIFEST.is_file():
        return {"manifest_file": False, "sha256sums_file": SUMS.is_file()}, []
    document = json.loads(MANIFEST.read_text(encoding="utf-8"))
    records = document.get("records", [])
    checks: list[dict[str, object]] = []
    for record in records:
        relative = Path(str(record["path"]))
        path = REPO / relative
        exists = path.is_file()
        actual = _sha256(path) if exists else None
        expected = str(record["sha256"])
        checks.append(
            {
                "path": relative.as_posix(),
                "role": record.get("role"),
                "exists": exists,
                "bytes_ok": exists and path.stat().st_size == int(record["bytes"]),
                "sha256_ok": exists and actual == expected,
            }
        )
    return {
        "manifest_file": True,
        "sha256sums_file": SUMS.is_file(),
        "records_complete": bool(records) and all(
            row["exists"] and row["bytes_ok"] and row["sha256_ok"] for row in checks
        ),
    }, checks


def check() -> dict[str, object]:
    required_code = [
        HERE / "run_geospatial_kernel.py",
        HERE / "run_geosos_flus.py",
        HERE / "run_planning_scenarios.py",
        HERE / "compile_comparison.py",
        HERE / "compile_planning.py",
        HERE / "export_planning_change_polygons.py",
        HERE / "audit_outputs.py",
        HERE / "shared.py",
        HERE / "planning.py",
        REPO / "data_agent/uwm/geospatial_kernel/runtime.py",
        HERE / "reproducibility/reproduce.py",
    ]
    required_manifests = [
        HERE / "planning_scenarios_public_2025_2031.json",
        HERE / "protocol.json",
        HERE / "boundary_manifest.json",
        HERE / "grid_profile.json",
        HERE / "reproducibility/requirements.lock.txt",
        HERE / "reproducibility/environment.json",
        MANIFEST,
        SUMS,
    ]
    external_assets = [
        HERE / "vendor/flus_console",
        HERE / "external/geofm_ldn/experiments/abu_dhabi/run_paper58_abu_dhabi.py",
        HERE / "external/geofm_ldn/experiments/paper8/paper58_runtime.py",
        HERE / "artifacts/predictions/paper58/seed_31/paper58_ldn.pt",
        HERE / "artifacts/predictions/paper58/seed_47/paper58_ldn.pt",
        HERE / "artifacts/predictions/paper58/seed_73/paper58_ldn.pt",
    ]
    code_rows = {_display(path): path.is_file() for path in required_code}
    manifest_rows = {_display(path): path.is_file() for path in required_manifests}
    external_rows = {
        _display(path): path.is_file() and (bool(path.stat().st_mode & 0o111) if path.name == "flus_console" else True)
        for path in external_assets
    }
    hash_summary, hash_rows = _manifest_checks()
    code_ok = all(code_rows.values())
    manifests_ok = all(manifest_rows.values())
    external_ok = all(external_rows.values())
    hash_ok = bool(hash_summary.get("records_complete"))
    status = "PASS" if code_ok and manifests_ok and external_ok and hash_ok else "BLOCKED"
    return {
        "schema": "gwm.abu_dhabi_reproducibility_check.v2",
        "benchmark_id": "abu-dhabi-land-use-v1",
        "created_at": datetime.now(UTC).isoformat(),
        "status": status,
        "python": sys.version.split()[0],
        "platform": {"system": platform.system(), "machine": platform.machine()},
        "code_and_manifests_complete": code_ok and manifests_ok,
        "external_dependencies_complete": external_ok,
        "environment_lock_complete": (HERE / "reproducibility/requirements.lock.txt").is_file()
        and (HERE / "reproducibility/environment.json").is_file(),
        "hash_manifest_complete": hash_ok,
        "checks": {
            "required_code": code_rows,
            "required_manifests": manifest_rows,
            "external_model_dependencies": external_rows,
            "hash_manifest": hash_summary,
        },
        "hash_records": hash_rows,
        "claim_boundary": "PASS means the checkout contains the declared public inputs and model assets and every declared hash matches. It does not claim that a private authoritative client dataset is present.",
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    report = check()
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(report, ensure_ascii=False, indent=2))
    raise SystemExit(0 if report["status"] == "PASS" else 2)


if __name__ == "__main__":
    main()
